def fmt_date(s: str | None) -> str:
    if not s:
        return "DRAFT - not yet scheduled"
    try:
        y, m, dd = s.split("-")
        return f"{int(m):d}/{int(dd):d}/{y}"
    except ValueError:
        return s


def header(deal, policy: dict) -> dict:
    t = deal.terms
    pol = [e for e in policy["exceptions"] if e["kind"] == "policy"]
    gl = [e for e in policy["exceptions"] if e["kind"] == "guideline"]
    def exc_text(e):
        return f"{e['item']} — required {e['requirement']}; actual {e['actual']}" + ("" if e["counts_toward_oversight"] else " (*)")
    seen = set()
    pol_items = []
    for e in pol:
        if e["item"] not in seen:
            seen.add(e["item"])
            pol_items.append(e["item"])
    return {"type": "header", "fund": t.fund_name or "INVEST DETROIT",
            "left": [t.borrower_name or "[Borrower]", t.borrower_address or "", f"Salesforce {t.salesforce_id}" if t.salesforce_id else "",
                     t.loan_number or ""],
            "right": ["INVESTMENT COMMITTEE", f"Date: {fmt_date(t.ic_date)}", f"Lender: {t.lender or '[Lender]'}",
                      f"Prepared by: {t.analyst or '[Underwriter]'} (draft generated by AI underwriting assistant)"],
            "request": t.request_summary or _default_request(deal),
            "policy_exceptions": pol_items or ["None identified"],
            "guideline_exceptions": [exc_text(e) for e in gl] or ["None identified"],
            "oversight": policy["oversight_council_required"],
            "exception_count": policy["guideline_exception_count"]}


def _default_request(deal) -> str:
    L = deal.terms.proposed_loan
    if not L:
        return "[Request amount and structure to be entered by the loan officer]"
    return f"Approval of an up to {fmt_money(L.amount)} loan" + (f" secured by {deal.terms.lien_position}" if deal.terms.lien_position else "") + "."


def qual(deal, key: str, what: str, fallback: str | None = None) -> dict:
    v = deal.terms.qualitative.get(key) or fallback
    return p(v, "input") if v else placeholder(what)


def benchmarking_section(naics: dict, bench: dict, deal_type: str) -> dict:
    blocks = []
    code = naics.get("code")
    if not code:
        return section("benchmarking", "Industry Benchmarking (NAICS)", [placeholder("NAICS code could not be determined")])
    ind = bench.get("industry")
    blocks.append(p(f"NAICS {code} — {naics.get('title')} (source: {naics.get('source')}). "
                    + (f"Benchmarked against IRS Statistics of Income tax year {ind['year']} aggregates for "
                       f"'{ind['label']}' ({ind['sector']}; {ind['returns']:,.0f} corporate returns)." if ind else "No IRS industry aggregate is mapped to this code.")))
    if bench.get("metrics"):
        rows = [row([m["metric"], _f(m["borrower"], m["fmt"]), _f(m["industry"], m["fmt"]), m["verdict"]]) for m in bench["metrics"]]
        blocks.append(table("Borrower vs. Industry" if deal_type == "small_business" else "Property vs. Industry",
                            ["Metric", "Borrower", "Industry", "Assessment"], rows, kind="grid",
                            footnote="Industry figures are aggregate ratios (sum of all corporations), not medians, and are weighted toward large firms; "
                                     "use them for direction, not as pass/fail thresholds."))
    if bench.get("realism"):
        rows = []
        for r in bench["realism"]:
            pv = r["projected"]
            bv = r["benchmark"]
            fmtk = r.get("fmt", "pct")
            if isinstance(bv, tuple):
                bs = f"{fmt_pct(bv[0])} - {fmt_pct(bv[1])}"
            else:
                bs = _f(bv, fmtk) if bv is not None else "n/a"
            rows.append(row([r["check"], _f(pv, fmtk), f"{bs} ({r['benchmark_label']})", r["result"]]))
        blocks.append(table("Projection Realism Checks", ["Check", "Projected", "Benchmark", "Result"], rows, kind="grid"))
    unf = [m["metric"] for m in bench.get("metrics", []) if m["verdict"] == "unfavorable"]
    fav = [m["metric"] for m in bench.get("metrics", []) if m["verdict"] == "favorable"]
    if unf or fav:
        blocks.append(p(("Compared with the industry, the borrower is favorable on " + ", ".join(fav) + ". " if fav else "")
                        + ("It is weaker on " + ", ".join(unf) + "." if unf else "")))
    if ind and ind.get("is_sector_total"):
        blocks.append(p("Only a sector-level benchmark was available for this code; interpret with caution."))
    return section("benchmarking", "Industry Benchmarking (NAICS)", blocks)


def compliance_section(policy: dict) -> dict:
    rows = []
    for e in policy["exceptions"]:
        rows.append(row([e["item"], e["requirement"], e["actual"], ("Policy exception" if e["kind"] == "policy" else "Guideline exception")
                         + ("" if e["counts_toward_oversight"] else " (*)")], "flag"))
    for item, req, actual in policy["passed"]:
        rows.append(row([item, req, actual, "Meets"]))
    blocks = [table(f"Credit Guidelines (rev. 4/2026) — {policy['product_label']}", ["Requirement", "Guideline", "This loan", "Result"], rows, kind="grid",
                    footnote="(*) Asterisked items in the Loan Product Matrix do not count toward the >3 exceptions that require Oversight Council approval.")]
    lob = policy.get("line_of_business")
    if lob:
        blocks.append(p(f"Line of business: {lob['line']} ({lob['reason']})."))
    blocks.append(p(f"Counted guideline exceptions: {policy['guideline_exception_count']}. "
                    + ("More than 3 — Oversight Council approval required." if policy["oversight_council_required"] else "Oversight Council approval is not triggered (3 or fewer).")))
    for e in policy["exceptions"]:
        if e["mitigants"]:
            blocks.append(p(f"Mitigants considered for {e['item'].lower()} (Appendix A hierarchy): " + "; ".join(e["mitigants"]) + "."))
    for i in policy["info"]:
        blocks.append(p(i))
    return section("compliance", "Credit Guideline Compliance", blocks)


def documents_section(policy: dict) -> dict:
    docs = policy["documents"]
    rows = [row([d["item"], "Before deal screen", d["requirement"], d["status"]], "flag" if d["status"] == "missing" and d["requirement"] == "required" else "")
            for d in docs["before_screen"]]
    rows += [row([d["item"], "During underwriting", d["requirement"], d["status"]]) for d in docs["underwriting"] if d["status"] == "missing"]
    return section("documents", "Outstanding Items (Appendix C Checklist)",
                   [table(None, ["Item", "When", "Requirement", "Status"], rows, kind="grid")])


def term_sheet_section(deal, analysis: dict, policy: dict) -> dict:
    t = deal.terms
    G = load_guidelines()
    prod = G["products"].get(t.product, {})
    L = t.proposed_loan
    rows = [("Borrower", t.borrower_name or ""), ("Product", prod.get("label", t.product))]
    if L:
        from ..engine.common import annual_debt_service, monthly_payment
        rows += [("Amount", f"Up to {fmt_money(L.amount)}"), ("Interest rate", f"{L.rate * 100:.2f}% fixed"),
                 ("Term", f"{L.term_months} months" if L.term_months else "[to be set; product max " + str(prod.get("max_term_months")) + " months]"),
                 ("Repayment", (f"Interest only for {L.io_months} months, then " if L.io_months else "") +
                  (f"P&I on a {L.amort_months // 12}-year amortization" if L.amort_months and L.amort_months % 12 == 0 else f"P&I on a {L.amort_months}-month amortization" if L.amort_months else "Interest only")),
                 ("Estimated payment", f"{fmt_money(L.annual_payment_override / 12 if L.annual_payment_override else monthly_payment(L.amount, L.rate, L.amort_months))} per month (P&I)")]
        if L.io_months:
            rows.append(("Interest reserve", deal.terms.qualitative.get("interest_holdback") or f"Interest during the first {L.io_months} months funded from an interest holdback."))
    fee = t.fee_pct
    rows.append(("Fees", (f"{fee * 100:.2f}% " if fee is not None else "") + f"(guideline: {prod.get('origination_fee_text') or (fmt_pct(prod.get('origination_fee'), 2) if prod.get('origination_fee') else 'n/a')})"))
    rows.append(("Collateral", t.lien_position or "; ".join(c.description for c in t.collateral) or "[collateral]"))
    rows.append(("Guarantees", "; ".join(t.guarantors) if t.guarantors else G["all_products"]["guarantees"]))
    rows.append(("Prepayment", "No prepayment penalty"))
    if prod.get("min_dscr"):
        rows.append(("Financial covenant", f"Minimum DSCR of {prod['min_dscr']:.2f}x tested annually" + (" at stabilization" if t.deal_type == "cre" else "")))
    rep = G["reporting_requirements"]
    groups = ["borrowing_entity", "individual_guarantors"] + (["real_estate"] if t.deal_type == "cre" else ["small_business"])
    items = [f"{r['item']} — {r['frequency']}, within {r['due']}" for g in groups for r in rep[g]]
    return section("term_sheet", "Draft Term Sheet (for discussion)", [kv(rows), subhead("Reporting requirements (Appendix D)"), bullets(items),
                   p("Draft terms are generated from the request and the Loan Product Matrix; the loan officer sets final pricing and structure.", "computed")])


def flags_section(flags: list) -> dict:
    order = {"critical": 0, "warning": 1, "info": 2}
    fl = sorted(flags, key=lambda f: order.get(f.severity, 3))
    seen, rows = set(), []
    for f in fl:
        if f.message in seen:
            continue
        seen.add(f.message)
        rows.append(row([f.severity.upper(), f.category.replace("_", " "), f.message, f.ref or ""], f.severity))
    return section("review_flags", "Underwriter Review Flags", [table(None, ["Severity", "Type", "Item", "Reference"], rows, kind="grid")])
